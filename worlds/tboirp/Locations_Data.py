class LocationData(NamedTuple):
    name: str
    code: Optional[int]
    region: str
    categories: list[str]
    repetitions: int # For locations where you need to do a task X number of times
    progress_type: Optional[LocationProgressType] # When None, don't parse to a Location
    custom: bool
    character: Optional[str] # The character related to this check, None otherwise
    access_rule: CollectionRule

    def full_name(self) -> str:
        """
        Returns the full name of the location (such as Mom's Heart Defeated (3x)
        """

        if self.repetitions == 1:
            return self.name

        return "{name} ({r}x)".format(name=self.name, r=self.repetitions)

